const assert=require('node:assert/strict');
const { _test:{ canSee,canEdit,normalized } }=require('../netlify/functions/leadership-home');
const admin={id:'admin-id',account_role:'cmc_admin',region:'East'};
const viewer={id:'president-id',account_role:'cmc_viewer',region:null};
const east={id:'east-id',account_role:'regional_leader',region:'East'};
const west={id:'west-id',account_role:'regional_leader',region:'Pacific'};
const shared={id:'id',kind:'meeting',visibility:'team',region:'East',created_by:east.id};
const personal={...shared,kind:'task',visibility:'personal'};
assert.equal(canSee(east,shared),true);
assert.equal(canSee(west,shared),false);
assert.equal(canSee(admin,shared),true);
assert.equal(canSee(viewer,shared),true);
assert.equal(canEdit(viewer,shared),false);
assert.equal(canEdit(west,shared),false);
assert.equal(canEdit(east,shared),true);
assert.equal(canSee(admin,personal),false);
assert.equal(canSee(viewer,personal),false);
assert.equal(canSee(east,personal),true);
assert.equal(canEdit(admin,personal),false);
assert.throws(()=>normalized({kind:'meeting',title:'Confidential',starts_at:'2026-11-14T15:00:00Z'},viewer),/read-only/);
assert.throws(()=>normalized({kind:'meeting',title:'',starts_at:'2026-11-14T15:00:00Z'},east),/title/);
assert.throws(()=>normalized({kind:'meeting',title:'Meeting'},east),/date/);
const created=normalized({kind:'meeting',title:'Regional planning',region:'Pacific',starts_at:'2026-11-14T15:00:00Z'},east);
assert.equal(created.region,'East');
assert.equal(created.starts_at,'2026-11-14T15:00:00.000Z');
const task=normalized({kind:'task',title:'Follow up',visibility:'personal',region:'Pacific',due_date:'2026-11-20'},east);
assert.equal(task.visibility,'personal');
assert.equal(task.region,'East');
assert.equal(task.due_date,'2026-11-20');
assert.throws(()=>normalized({kind:'task',title:'Follow up',due_date:'bad'},east),/date/);
console.log('Leadership home role and input tests passed');
